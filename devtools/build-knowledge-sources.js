/**
 * WRITE THE SOURCE MANIFEST THE PRODUCT CAN ACTUALLY READ.
 *
 *     node devtools/build-knowledge-sources.js
 *
 * knowledge/MANIFEST.md has always claimed the shipped corpus is "re-fetchable
 * from the URLs recorded here", and has never recorded a URL. The URLs live in
 * devtools/fetch-knowledge.js, which a packaged build does not ship — so an
 * installed copy of .lcl knew a document's title, page count and entire
 * extracted text, and could say nothing about it but "not on disk". That is
 * contract K6's whole subject: a document whose source was never downloaded
 * must say exactly that and offer the fetch, never "not on disk".
 *
 * This writes knowledge/sources.json, which IS shipped (app/builder-config.json
 * lists it beside index.json and MANIFEST.md), keyed by the corpus-relative path
 * so main.js can look a document up by the same `source` field shelf.json
 * already carries.
 *
 * NO NETWORK. It reads an array out of a sibling file and writes JSON. The
 * fetcher's own download path stays behind `require.main === module`.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const { DOCS } = require("./fetch-knowledge.js");

const docs = {};
for (const d of DOCS) {
    // `into` is repo-relative ("knowledge/physics"); the key is corpus-relative
    // ("physics/Foo.pdf"), which is what shelf.json's `source` field holds.
    const rel = String(d.into).replace(/^knowledge[\\/]/, "") + "/" + d.file;
    docs[rel] = { url: d.url, licence: d.licence || null };
}

const out = {
    builtAt: new Date().toISOString(),
    note: "Where each shipped document came from. Generated by " +
          "devtools/build-knowledge-sources.js from devtools/fetch-knowledge.js, " +
          "which remains the single source of truth. Keyed by the same " +
          "corpus-relative path knowledge/text/shelf.json records as `source`.",
    count: Object.keys(docs).length,
    docs
};

const dest = path.join(ROOT, "knowledge", "sources.json");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, JSON.stringify(out, null, 1));
console.log(`wrote ${path.relative(ROOT, dest)} — ${out.count} documents`);
