/**
 * TURN THE INDEX BACK INTO SOMETHING A PERSON CAN READ.
 *
 * The shipped corpus is 907 MB of PDFs. The installer cannot carry that — NSIS
 * tops out around 2 GB and the build is already 1.5 GB — so builder-config.json
 * ships only index.json, vectors.f32 and MANIFEST.md out of knowledge/.
 *
 * Which produced exactly the report it had to:
 *
 *     "Read the knowledge opens a pop up, that says there is nothing there.
 *      Knowledge libraries has things. i click on physics. i see the cards.
 *      i can not click to open and read the full content of anything"
 *
 * Both halves of that are the same cause. The library view reads index.json, so
 * it lists 64 books. The reader globbed for *.pdf, found none, and said the
 * shelf was empty; and every card pointed at a file that was not installed.
 *
 * The text itself was never missing. index.json is 68 MB and 50 MB of that is
 * the extracted page text of every document — already shipped, just locked
 * inside a structure built for embedding lookups rather than for reading.
 *
 * So this unpacks it: one .txt per document, pages marked, plus a shelf.json
 * describing what is there. 50 MB, no PDFs, opens instantly because reading a
 * page no longer means parsing a 68 MB JSON in the main process.
 *
 *     node devtools/build-knowledge-text.js
 *
 * Run after any reindex. tests/knowledge.js fails if the two drift apart.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const KROOT = path.join(ROOT, "knowledge");
const OUT = path.join(KROOT, "text");

/** "page 12" -> 12. Chunk locs are human strings, not numbers. */
function pageOf(loc) {
    const m = String(loc || "").match(/(\d+)/);
    return m ? Number(m[1]) : 0;
}

/** physics/Light-and-Matter-Benjamin-Crowell---algebra-based.pdf -> a title */
function titleOf(file) {
    return path.basename(file).replace(/\.[a-z0-9]+$/i, "")
        .replace(/-+/g, " ")
        .replace(/\s+/g, " ")
        .trim();
}

function main() {
    const indexPath = path.join(KROOT, "index.json");
    if (!fs.existsSync(indexPath)) {
        console.error("no knowledge/index.json — run the indexer first");
        process.exit(1);
    }

    console.log("reading index.json…");
    const idx = JSON.parse(fs.readFileSync(indexPath, "utf8"));
    const chunks = Array.isArray(idx.chunks) ? idx.chunks : [];
    if (!chunks.length) {
        console.error("index.json has no chunks");
        process.exit(1);
    }

    // group by document, then order by page
    const byFile = new Map();
    for (const c of chunks) {
        if (!c || !c.file || typeof c.text !== "string") continue;
        if (!byFile.has(c.file)) byFile.set(c.file, []);
        byFile.get(c.file).push(c);
    }

    fs.rmSync(OUT, { recursive: true, force: true });
    fs.mkdirSync(OUT, { recursive: true });

    const subjects = new Map();
    let totalBytes = 0;

    for (const [file, list] of [...byFile].sort((a, b) => a[0].localeCompare(b[0]))) {
        const subject = file.includes("/") ? file.split("/")[0] : "general";
        // MANIFEST.md is the corpus's own provenance note; it belongs in the
        // library card, not on the shelf as a book
        if (!file.includes("/")) continue;

        list.sort((a, b) => pageOf(a.loc) - pageOf(b.loc));

        // One page per record, chunks within a page joined in order. The marker
        // is what the reader seeks on, so it has to be unambiguous and it has to
        // survive being read as plain text by a human.
        const pages = new Map();
        for (const c of list) {
            const p = pageOf(c.loc) || 1;
            if (!pages.has(p)) pages.set(p, []);
            pages.get(p).push(c.text);
        }

        const ordered = [...pages.keys()].sort((a, b) => a - b);
        const body = ordered
            .map(p => `\f[page ${p}]\n${pages.get(p).join("\n\n").trim()}\n`)
            .join("\n");

        const rel = file.replace(/\.[a-z0-9]+$/i, "") + ".txt";
        const dest = path.join(OUT, rel);
        fs.mkdirSync(path.dirname(dest), { recursive: true });
        fs.writeFileSync(dest, body, "utf8");

        const bytes = Buffer.byteLength(body, "utf8");
        totalBytes += bytes;

        if (!subjects.has(subject)) subjects.set(subject, []);
        subjects.get(subject).push({
            file: rel,                       // path under knowledge/text
            source: file,                    // the pdf it came from, for citation
            title: titleOf(file),
            pages: ordered.length,
            firstPage: ordered[0] || 1,
            lastPage: ordered[ordered.length - 1] || 1,
            bytes
        });
    }

    const shelf = {
        builtAt: new Date().toISOString(),
        note: "Extracted text of the built-in library. Generated by " +
              "devtools/build-knowledge-text.js from knowledge/index.json.",
        subjects: [...subjects]
            .map(([name, docs]) => ({
                name,
                docs: docs.sort((a, b) => a.title.localeCompare(b.title))
            }))
            .sort((a, b) => b.docs.length - a.docs.length)
    };
    fs.writeFileSync(path.join(OUT, "shelf.json"), JSON.stringify(shelf, null, 1), "utf8");

    const docCount = shelf.subjects.reduce((n, s) => n + s.docs.length, 0);
    console.log(`\n  ${docCount} documents across ${shelf.subjects.length} subjects`);
    for (const s of shelf.subjects) {
        const mb = s.docs.reduce((n, d) => n + d.bytes, 0) / 1e6;
        console.log(`    ${String(s.docs.length).padStart(3)}  ${s.name.padEnd(14)} ${mb.toFixed(1)} MB`);
    }
    console.log(`\n  ${(totalBytes / 1e6).toFixed(1)} MB written to knowledge/text/`);
}

main();
